class SMAwareKernelGenerator:
    """
    AI-driven SM-aware kernel generator.

    Generates and iteratively optimizes Triton kernels for different
    SM partition sizes using wave efficiency analysis.
    """

    def __init__(
        self,
        model_name: str = "gpt-4",
        api_key: Optional[str] = None,
        base_url: Optional[str] = None,
    ):
        self.model_name = model_name
        self.api_key = api_key or os.getenv("LLM_API_KEY")
        self.base_url = base_url

        if self.api_key is None:
            print("Warning: No API key set. Use generate_sm_aware_kernel() for rule-based generation.")

    def generate(
        self,
        M: int, N: int, K: int,
        num_sms: int,
        use_ai: bool = True,
    ) -> str:
        """
        Generate kernel code.

        Args:
            M, N, K: Matrix dimensions
            num_sms: SM partition size
            use_ai: If True and API key available, use LLM. Otherwise use rule-based.

        Returns:
            Python kernel code string
        """
        if not use_ai or self.api_key is None:
            return generate_sm_aware_kernel(M, N, K, num_sms)

        # AI generation path (similar to FlashInfer-Bench)
        try:
            import openai
            client = openai.OpenAI(api_key=self.api_key, base_url=self.base_url)

            prompt = self._build_prompt(M, N, K, num_sms)
            response = client.chat.completions.create(
                model=self.model_name,
                messages=[{"role": "user", "content": prompt}],
            )
            code = response.choices[0].message.content

            # Clean code
            code = self._clean_code(code)
            return code

        except ImportError:
            print("openai not installed, falling back to rule-based")
            return generate_sm_aware_kernel(M, N, K, num_sms)

    def _build_prompt(self, M: int, N: int, K: int, num_sms: int) -> str:
        """Build prompt for LLM kernel generation."""
        best_cfg = suggest_optimal_block_size(M, N, num_sms)
        wave_info = f"Best block size: {best_cfg[0]}x{best_cfg[1]}, efficiency: {best_cfg[2]['overall_efficiency']*100:.1f}%"

        return f"""Generate a Triton GEMM kernel optimized for wave efficiency.

## Task
- Operation: C = A @ B where A is {M}x{K}, B is {K}x{N}
- Target SM count: {num_sms}
- Data type: float16

## SM-Aware Optimization Critical Points

1. **Add NUM_SMS to autotune key**: `key=['M', 'N', 'K', 'NUM_SMS']`
2. **Pass NUM_SMS as tl.constexpr**: It forces Triton to re-tune for each SM count
3. **Wave Efficiency Analysis**: {wave_info}

## Wave Quantization Problem
- Blocks = ceil(M/BLOCK_M) × ceil(N/BLOCK_N)
- Waves = ceil(Blocks / NUM_SMS)
- Last wave often has idle SMs

## Config Strategy for {num_sms} SMs
- Choose BLOCK_M × BLOCK_N such that Blocks ≈ k × NUM_SMS for some integer k
- Smaller blocks = more blocks = better wave fill (but more overhead)
- Larger blocks = fewer blocks = better L2 reuse (but risk wave waste)

## Requirements
- Use `@triton.autotune` with multiple configs
- Include NUM_SMS in autotune key
- Provide `run(A, B, C, M, N, K, NUM_SMS)` entry point
- Handle boundary masking properly
- Match torch.matmul reference

Generate the complete kernel code:
"""

    def _clean_code(self, code: str) -> str:
        """Clean generated code."""
        # Remove markdown code blocks
        if "```python" in code:
            code = code.split("```python")[1]
        if "```" in code:
            code = code.split("```")[0]
        return code.strip()


