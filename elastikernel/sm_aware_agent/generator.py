@dataclass
class TritonConfig:
    """Triton autotune configuration."""
    block_m: int
    block_n: int
    block_k: int
    group_size_m: int = 8
    num_stages: int = 3
    num_warps: int = 4

    def to_triton_config(self):
        """Convert to triton.Config dict."""
        return {
            'BLOCK_SIZE_M': self.block_m,
            'BLOCK_SIZE_N': self.block_n,
            'BLOCK_SIZE_K': self.block_k,
            'GROUP_SIZE_M': self.group_size_m,
        }

    def __str__(self) -> str:
        return f"M={self.block_m},N={self.block_n},K={self.block_k},G={self.group_size_m}"


